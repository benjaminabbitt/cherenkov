#!/usr/bin/env bash
# Regenerate crates/cherenkov-dap-types/src/generated.rs from the checked-in
# DAP JSON schema. To move to a newer protocol version, replace
# schema/debugAdapterProtocol.json (from SCHEMA_URL) and rerun.
set -euo pipefail

TYPIFY_VERSION=0.10.1
SCHEMA_URL=https://microsoft.github.io/debug-adapter-protocol/debugAdapterProtocol.json
crate="$(cd "$(dirname "$0")/.." && pwd)/crates/cherenkov-dap-types"

if [[ "${1:-}" == "--fetch" ]]; then
    curl -sSfL -o "$crate/schema/debugAdapterProtocol.json" "$SCHEMA_URL"
fi

if ! cargo typify --version 2>/dev/null | grep -q "$TYPIFY_VERSION"; then
    echo "need cargo-typify $TYPIFY_VERSION: cargo install cargo-typify@$TYPIFY_VERSION" >&2
    exit 1
fi

out="$crate/src/generated.rs"
cargo typify --no-builder "$crate/schema/debugAdapterProtocol.json" -o "$out.tmp"
{
    echo "// @generated by scripts/gen-dap-types.sh (cargo-typify $TYPIFY_VERSION)"
    echo "// from schema/debugAdapterProtocol.json. Do not edit."
    cat "$out.tmp"
} > "$out"
rm "$out.tmp"
rustfmt --edition 2024 "$out"
